/**
 * Company profile PDF for a locale. Files are generated by `npm run profile`
 * into public/profile/. Plain <a> hrefs don't get basePath, so it is added here.
 */
export function profilePdfHref(locale: string) {
  const lang = locale === "ar" ? "ar" : "en";
  return `${process.env.NEXT_PUBLIC_BASE_PATH ?? ""}/profile/watermark-it-company-profile-${lang}.pdf`;
}
